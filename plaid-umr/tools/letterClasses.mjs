// Writes the character class planWordSplits counts to choose the half of a
// split word a node stays on, as code-point ranges: src/domain/letterClasses.js.
// Run from plaid-umr: `node tools/letterClasses.mjs`.
//
// The count used to ask the runtime (`/[\p{L}\p{N}]/u`), so its answer moved
// with the browser's or node's Unicode version, and the same open could cut a
// node differently in two browsers. Marks count too: in Devanagari or Bengali a
// vowel sign is part of the letter it follows, and leaving it out made the half
// with fewer letters look longer.
//
// UNICODE is pinned, as in plaid-igt/tools/punctuationClasses.mjs (see
// requireUnicode).

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { packRanges, rangesOf, requireUnicode } from '../../plaid-ui/tools/unicodeRanges.mjs';

const UNICODE = '16.0';
requireUnicode(UNICODE);

const letters = rangesOf(/[\p{L}\p{M}\p{N}]/u);

writeFileSync(
  resolve('src/domain/letterClasses.js'),
  `// Generated by tools/letterClasses.mjs (Unicode ${UNICODE}). Do not edit.
// Inclusive code-point ranges, sorted, packed (plaid-ui's unicodeRanges.js).

import { inRanges, unpackRanges } from '../../../plaid-ui/src/lib/unicodeRanges.js';

/** \`/[\\p{L}\\p{M}\\p{N}]/u\`: letters, marks and digits. */
export const LETTER_MARK_OR_NUMBER = unpackRanges(
  '${packRanges(letters)}',
);

/** Is the first code point of \`c\` a letter, a mark or a digit? */
export const isLetterMarkOrNumber = (c) => inRanges(LETTER_MARK_OR_NUMBER, c);
`,
);
console.log(`${letters.length} letter, mark and number ranges`);
