// Writes the character classes the ignored-tokens rule and the built-in
// tokenizer read, as code-point ranges: plaid-ui's
// src/domain/punctuationClasses.js (igtWordBreaks.js, igt's import/align.js),
// plaid-client-py's workflows/igt/punctuation_classes.py (ignored.py) and
// plaid-core's resources/punctuation_classes.txt (the text rules' `punct?`, and the
// break class core's "Tokenize new text" cuts at). Run from
// plaid-igt: `node tools/punctuationClasses.mjs`.
//
// The rule used to ask the runtime (`/[\p{P}\p{S}]/u`,
// `/\p{Extended_Pictographic}/u`), so its answer moved with the browser's or
// node's Unicode version: ★ is a pictograph in Unicode 16 and not in 17, and so
// it was a word in one browser and ignored in another, and Python, which had a
// table, disagreed with whichever node ran the comparison. One table, written
// here for both languages, answers the same everywhere. A word reference
// (`s3.w2`) counts words past the ignored tokens, so the agreement is what
// keeps those references valid.
//
// UNICODE is pinned. Moving it is a deliberate change: it changes which tokens
// existing documents ignore, and so the numbering of later words. Run this
// with a node whose `process.versions.unicode` is the new one, and set it here.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { packRanges, rangesOf, requireUnicode } from '../../plaid-ui/tools/unicodeRanges.mjs';

const UNICODE = '16.0';
requireUnicode(UNICODE);

const punct = rangesOf(/[\p{P}\p{S}]/u);
const picto = rangesOf(/\p{Extended_Pictographic}/u);
// The built-in tokenizer's break class (plaid-ui igtWordBreaks.js
// `isUnicodePunctuation`), which core's "Tokenize new text" cuts at too: \p{P}
// and 24 ASCII and Latin-1 symbols and the soft hyphen, $ + < = > ^ ` | ~ ¢ £ ¤
// ¥ ¦ ¨ © ¬ SHY ® ¯ ° ± ´ ¸, which turn up in transcription and want to break a
// word ("=" is the clitic marker). Not [\p{P}\p{S}], which adds every arrow,
// math operator and box-drawing character.
const brk = rangesOf(/[\p{P}$+<=>^`|~\u00A2-\u00A6\u00A8\u00A9\u00AC-\u00B1\u00B4\u00B8]/u);

const hex = (cp, upper) => {
  const h = cp.toString(16).padStart(4, '0');
  return `0x${upper ? h.toUpperCase() : h}`;
};
const pyRanges = (rs) => {
  const rows = [];
  for (let i = 0; i < rs.length; i += 5) {
    rows.push(
      '    ' +
        rs
          .slice(i, i + 5)
          .map(([a, b]) => `(${hex(a, true)}, ${hex(b, true)}),`)
          .join(' '),
    );
  }
  return rows.join('\n');
};

writeFileSync(
  resolve('../plaid-ui/src/domain/punctuationClasses.js'),
  `// Generated by plaid-igt/tools/punctuationClasses.mjs (Unicode ${UNICODE}). Do not edit.
// Inclusive code-point ranges, sorted, packed (plaid-ui's unicodeRanges.js).
// plaid-client-py's workflows/igt/punctuation_classes.py is written from the
// same run.

import { inRanges, unpackRanges } from '../lib/unicodeRanges.js';

/** \`/[\\p{P}\\p{S}]/u\`: punctuation and symbols. */
export const PUNCT_OR_SYMBOL = unpackRanges(
  '${packRanges(punct)}',
);

/** \`/\\p{Extended_Pictographic}/u\`: emoji and the like. */
export const PICTOGRAPHIC = unpackRanges(
  '${packRanges(picto)}',
);

/** The built-in tokenizer's break class: \\p{P} and 24 Latin-1 symbols. */
const WORD_BREAK = unpackRanges(
  '${packRanges(brk)}',
);

/** Is the first code point of \`c\` punctuation or a symbol? */
export const isPunctOrSymbol = (c) => inRanges(PUNCT_OR_SYMBOL, c);

/** Is the first code point of \`c\` a pictograph? */
export const isPictograph = (c) => inRanges(PICTOGRAPHIC, c);

/** Does the first code point of \`c\` break a word? */
export const isWordBreak = (c) => inRanges(WORD_BREAK, c);
`,
);
writeFileSync(
  resolve('../plaid-client-py/src/plaid_client/workflows/igt/punctuation_classes.py'),
  `"""Generated by plaid-igt/tools/punctuationClasses.mjs (Unicode ${UNICODE}). Do not edit.

Inclusive code-point ranges, sorted. plaid-ui's
src/domain/punctuationClasses.js is written from the same run.
"""

#: \`\`/[\\p{P}\\p{S}]/u\`\`: punctuation and symbols.
PUNCT_OR_SYMBOL = (
${pyRanges(punct)}
)

#: \`\`/\\p{Extended_Pictographic}/u\`\`: emoji and the like.
PICTOGRAPHIC = (
${pyRanges(picto)}
)

#: The built-in tokenizer's break class: \\p{P} and 24 Latin-1 symbols.
WORD_BREAK = (
${pyRanges(brk)}
)
`,
);
writeFileSync(
  resolve('../plaid-core/resources/punctuation_classes.txt'),
  `# Generated by plaid-igt/tools/punctuationClasses.mjs (Unicode ${UNICODE}). Do not edit.
# Inclusive hex code-point ranges, as plaid-ui's src/domain/punctuationClasses.js
# packs them: punct is [\\p{P}\\p{S}], picto is \\p{Extended_Pictographic},
# break is the built-in tokenizer's break class, \\p{P} and 24 Latin-1 symbols.
punct ${packRanges(punct)}
picto ${packRanges(picto)}
break ${packRanges(brk)}
`,
);
console.log(`${punct.length} punctuation, ${picto.length} pictograph, ${brk.length} break ranges`);
