// Writes plaid-core's resources/spaceless_scripts.txt: the code points of the
// scripts written without spaces between words, as code-point ranges, which
// core's "Tokenize new text" reads to leave such text without words.
// Run from plaid-igt: `node tools/spacelessScripts.mjs`.
//
// A table, not the runtime's `\p{Script=...}`, so the answer does not move with
// Java's Unicode version (see tools/punctuationClasses.mjs). UNICODE is pinned
// the same way: run with a node whose `process.versions.unicode` is it.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { packRanges, rangesOf, requireUnicode } from '../../plaid-ui/tools/unicodeRanges.mjs';

const UNICODE = '16.0';
requireUnicode(UNICODE);

// Scripts whose writing puts no space between words. By Script, not
// Script_Extensions, so shared punctuation (。, ・) stays out.
const SCRIPTS = [
  'Han',
  'Hiragana',
  'Katakana',
  'Bopomofo',
  'Yi',
  'Thai',
  'Lao',
  'Khmer',
  'Myanmar',
  'Tibetan',
  'Tai_Le',
  'New_Tai_Lue',
  'Tai_Tham',
  'Tai_Viet',
  'Balinese',
  'Javanese',
];

const ranges = rangesOf(new RegExp(`[${SCRIPTS.map((s) => `\\p{Script=${s}}`).join('')}]`, 'u'));

writeFileSync(
  resolve('../plaid-core/resources/spaceless_scripts.txt'),
  `# Generated by plaid-igt/tools/spacelessScripts.mjs (Unicode ${UNICODE}). Do not edit.
# Inclusive hex code-point ranges, as plaid-core's punctuation_classes.txt has
# them: the scripts written without spaces between words
# (${SCRIPTS.join(', ')}).
spaceless ${packRanges(ranges)}
`,
);
console.log(`${ranges.length} ranges`);
