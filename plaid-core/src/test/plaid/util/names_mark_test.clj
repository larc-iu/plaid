;; Which patterns name a combining mark, so the server's REGEXP also
;; matches them decomposed (REV7-CORE-4). The same table as plaid-agent's
;; tests/test_canonical_match.py and plaid-ui's javaRegex.test.js.
(ns plaid.util.names-mark-test
  (:require [clojure.test :refer [deftest is]]
            [plaid.util.canonical :as canonical]))

(def ^:private cases
  [["\u0301" true]
   ["\\x{301}" true]
   ["\\u0301" true]
   ["\\x{0301}" true]
   ["[\u0301]" true]
   ["[\\x{300}-\\x{36f}]" true]
   ["[\u0300-\u036f]" true]
   ["\\p{M}" true]
   ["\\p{Mn}" true]
   ["a|\u0301" true]
   ["\\Q\u0301\\E" true]
   ["\\pM" true]
   ["\\p{IsMn}" true]
   ["\\p{gc=Mc}" true]
   ["\\p{InCombiningDiacriticalMarks}" true]
   ["\\p{Mark}" true]
   ["\\p{general_category=Nonspacing_Mark}" true]
   ["[\\p{Mn}\\p{Me}]" true]
   ["[a\\x{301}]" true]
   ["[\\p{M}]" true]
   ["[[\\p{M}]a]" true]
   ["\\x30\u0301" true]
   ["a" false]
   ["a." false]
   ["\\w" false]
   ["[a-z]" false]
   ["\\p{L}" false]
   ["\\P{M}" false]
   ["\\\\x{301}" false]
   ["\\x41" false]
   ["[\\x{2f0}-\\x{310}]" false]
   ["\\p{IsLatin}" false]
   ["[a-]" false]
   ["\\x{zz}" false]
   ["[^\\p{Me}]" false]
   ["\\x{110000}" false]
   ["\\x{1F600}" false]
   ["[\\p{L}\\p{M}]" false]
   ["\\b" false]
   ["\\W" false]
   ["a\\w" false]
   ["[^\\x{301}]" true]
   ["[\\x{2ff}-\\x{370}]" false]
   ;; REV8-CORE-6
   ["\\N{COMBINING ACUTE ACCENT}" true]
   ["\\N{combining acute accent}" true]
   ["[\\N{COMBINING GRAVE ACCENT}a]" true]
   ["\\N{LATIN SMALL LETTER A WITH ACUTE}" false]
   ["\\N{NO SUCH NAME}" false]
   ["[^\\P{M}]" true]
   ["[^\\P{Mn}]" true]
   ["[^\\P{M}a]" false]
   ["[\\P{M}]" false]
   ["\\P{M}" false]
   ["[^\\P{M}\\p{M}]" false]])

(deftest names-mark-reads-a-pattern-as-the-clients-do
  (doseq [[pattern named] cases]
    (is (= named (canonical/names-mark? pattern)) pattern)))

;; How a pattern naming a mark is matched against a value in NFD
;; (REV8-CORE-1). The same table as plaid-agent's tests/test_canonical_match.py
;; and plaid-ui's javaRegex.test.js.
(def ^:private decomposed-cases
  [["\u00e1" "a\u0301"]
   ["x\u00e1y" "xa\u0301y"]
   ["[\u00e1\\x{301}]" "(?:a\u0301|[\u00e1\\x{301}])"]
   ["[\u00f3\u00fa\u0301]" "(?:o\u0301|u\u0301|[\u00f3\u00fa\u0301])"]
   ["[^\u00e1\\x{301}]" "(?:(?!a\u0301)[^\u00e1\\x{301}])"]
   ["[^\u00e1]+" "(?:(?!a\u0301)[^\u00e1])+"]
   ["[^\u00e1&&b]" "[^a\u0301&&b]"]
   ["[x[^\u00e1]]" "[x[^a\u0301]]"]
   ["[^x[\u00e1]]" "[^x[a\u0301]]"]
   ["[[\u00e1]\u00e9]" "(?:e\u0301|[[\u00e1]\u00e9])"]
   ["[\u00e1\u00e1]" "(?:a\u0301|[\u00e1\u00e1])"]
   ["[\u1ea5\u00e2]" "(?:a\u0302\u0301|a\u0302|[\u1ea5\u00e2])"]
   ["[\\x{e1}b]" "(?:a\u0301|[\\x{e1}b])"]
   ["[\\u00e1]" "(?:a\u0301|[\\u00e1])"]
   ["[\\\u00e1]" "(?:a\u0301|[\\\u00e1])"]
   ["[\u00e0-\u00fa]" "[\u00e0-\u00fa]"]
   ["[a-\u00fa\u00e9]" "(?:e\u0301|[a-\u00fa\u00e9])"]
   ["[\u00e1&&\\p{L}]" "[\u00e1&&\\p{L}]"]
   ["[\u00e1-]" "(?:a\u0301|[\u00e1-])"]
   ["[\\Q\u00e1]\\E]" "(?:a\u0301|[\\Q\u00e1]\\E])"]
   ["[\u00e1]+" "(?:a\u0301|[\u00e1])+"]
   ["\u00e9+" "(?:e\u0301)+"]
   ["\u00e9{2}" "(?:e\u0301){2}"]
   ["\u00e9*?" "(?:e\u0301)*?"]
   ["a\u00e9?" "a(?:e\u0301)?"]
   ["(\u00e9)+" "(e\u0301)+"]
   ["\u00e9{x" "e\u0301{x"]
   ["\\x{e9}+" "\\x{e9}+"]
   ["\\\u00e9" "\\\u00e9"]
   ["\\p{L}\u00e9" "\\p{L}e\u0301"]
   ["\\Q\u00e9\\E+" "\\Q\\E(?:\\Qe\u0301\\E)+"]
   ["\\Q\u00e1\u00e9\\E" "\\Qa\u0301e\u0301\\E"]
   ["\\Q\u00e1" "\\Qa\u0301"]
   ["\u1ea1\u0301" "a\u0323\u0301"]
   ["\u00e1\u0323" "a\u0323\u0301"]
   ["[]\u00e1]" "(?:a\u0301|[]\u00e1])"]
   ["[^]\u00e1]" "(?:(?!a\u0301)[^]\u00e1])"]
   ["[x[]\u00e1]]" "[x[]\u00e1]]"]
   ["[^x[\u00fa-\u1ea5\u00e1]]" "[^x[\u00fa-\u1ea5a\u0301]]"]])

(deftest decompose-pattern-keeps-class-letters
  (doseq [[pattern want] decomposed-cases]
    (is (= want (canonical/decompose-pattern pattern)) pattern)))
